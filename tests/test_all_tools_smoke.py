def make_inputs():
    image = None
    try:
        from PIL import Image

        image = Image.new("RGB", (32, 24), (45, 212, 196))
    except Exception:
        pass
    file_path = os.path.join(tempfile.gettempdir(), "texttools-smoke.txt")
    with open(file_path, "w", encoding="utf-8") as fh:
        fh.write("hello")
    return image, file_path


def main():
    image, file_path = make_inputs()
    failures = []
    skipped = []
    for tool in ALL_TOOLS:
        if tool.id in NETWORK_LIVE:
            skipped.append(tool.id)
            continue
        if tool.id in MEDIA_IDS:
            if image is None:
                skipped.append(tool.id)
                continue
            item = Input(text=SAMPLES.get(tool.id, ""), image=image)
        elif tool.id in FILE_IDS:
            item = Input(text=file_path, files=[file_path])
        else:
            item = Input(text=SAMPLES.get(tool.id, "test"))
        try:
            tool.run(item)
        except ToolError:
            pass
        except Exception as exc:
            failures.append((tool.id, type(exc).__name__, str(exc)))
    print(f"ran {len(ALL_TOOLS) - len(skipped)} tools, skipped {len(skipped)}")
    if failures:
        for tool_id, kind, message in failures:
            print(f"FAIL {tool_id}: {kind}: {message}")
        raise SystemExit(1)
    print("all tools completed without unexpected exceptions")


if __name__ == "__main__":
    main()
